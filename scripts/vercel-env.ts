/**
 * `pnpm vercel:env [--app-url https://…] [--env production|preview] [--out path]`
 *
 * Reads .env.local and writes a shell script of `vercel env add NAME <env>` commands, each
 * fed its value on stdin (printf … | vercel env add). Values are NEVER printed: the script is
 * written with mode 600 and only variable names go to stdout. Run the script, then delete it.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { parse } from "dotenv";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  if (i !== -1) return process.argv[i + 1];
  const eq = process.argv.find((a) => a.startsWith(`--${name}=`));
  return eq?.slice(name.length + 3);
}

const target = arg("env") ?? "production";
if (!["production", "preview", "development"].includes(target)) {
  console.error(`--env must be production, preview or development (got ${target})`);
  process.exit(1);
}
const appUrl = arg("app-url");
if (appUrl !== undefined && !/^https?:\/\/[^\s/]+/.test(appUrl)) {
  console.error("--app-url must be an absolute URL, e.g. https://yukikaki.example.jp");
  process.exit(1);
}
const outFile =
  arg("out") ?? path.join(process.env.HERMES_SCRATCH ?? path.join(os.homedir(), ".hermes", "cache", "scratch"), "vercel-env.sh");

const envFile = path.resolve(".env.local");
if (!existsSync(envFile)) {
  console.error(".env.local not found — run from the repo root");
  process.exit(1);
}
const local = parse(readFileSync(envFile));
const expected = Object.keys(parse(readFileSync(path.resolve(".env.example"))));

// Local-only variables that must not be pushed to Vercel.
const SKIP = new Set(["PGLITE_DIR"]);

const values: Record<string, string> = {};
for (const [k, v] of Object.entries(local)) if (!SKIP.has(k) && v !== "") values[k] = v;
if (appUrl) values.APP_URL = appUrl.replace(/\/+$/, "");

// Single-quote for POSIX sh; values never contain a trailing newline (printf '%s').
const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

const names = Object.keys(values).sort();
const lines = [
  "#!/bin/sh",
  `# Generated by pnpm vercel:env — contains secrets. Run once from the linked repo, then delete.`,
  "set -eu",
  ...names.flatMap((k) => [
    `vercel env rm ${k} ${target} --yes >/dev/null 2>&1 || true`,
    `printf '%s' ${sq(values[k])} | vercel env add ${k} ${target}`,
  ]),
  "",
];
mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), { mode: 0o600 });
chmodSync(outFile, 0o600);

console.log(`Wrote ${names.length} variables for "${target}" to ${outFile} (mode 600):`);
for (const k of names) console.log(`  ${k}${k === "APP_URL" && appUrl ? "  (from --app-url)" : ""}`);
const missing = expected.filter((k) => !SKIP.has(k) && !(k in values));
if (missing.length) console.log(`\nMissing / empty in .env.local (not written): ${missing.join(", ")}`);
if (!appUrl && /localhost|127\.0\.0\.1/.test(values.APP_URL ?? ""))
  console.log("\n⚠ APP_URL points at localhost — rerun with --app-url https://<your-domain>");
if (/^pk_test_|^sk_test_/.test(values.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY ?? "") || /^sk_test_/.test(values.CLERK_SECRET_KEY ?? ""))
  console.log("⚠ Clerk keys are development (test) keys — use the production instance's pk_live_/sk_live_ keys");
if (/onboarding@resend\.dev/.test(values.EMAIL_FROM ?? ""))
  console.log("⚠ EMAIL_FROM uses the Resend test sender — set a verified-domain address");
console.log(`\nNext: vercel link && sh ${outFile} && rm ${outFile}`);
